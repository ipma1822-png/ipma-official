-- 회원가입 신청이 'approved'로 바뀌는 순간 자동 공개피드 생성
create or replace function public.gms_feed_from_application()
returns trigger language plpgsql security definer set search_path=public as $$
declare j jsonb:=to_jsonb(new); oldj jsonb:=case when tg_op='UPDATE' then to_jsonb(old) else '{}'::jsonb end;
        v_status text:=lower(coalesce(j->>'status',''));
        v_old_status text:=lower(coalesce(oldj->>'status',''));
        v_org text; v_name text; v_type text:='new_member'; v_detail text;
begin
  if v_status <> 'approved' or v_old_status='approved' then return new; end if;
  if tg_table_name='ipma_member_applications' then v_org:='IPMA';
  elsif tg_table_name='wtkf_member_applications' then v_org:='WTKF';
  elsif tg_table_name='idp_member_applications' then v_org:='IDP';
  elsif tg_table_name='idp_branch_applications' then v_org:='IDP'; v_type:='new_branch';
  else return new; end if;
  v_name:=coalesce(j->>'name',j->>'applicant_name',j->>'branch_name',j->>'representative_name');
  if v_type='new_member' then v_detail:='신규 회원이 등록되었습니다.'; else v_detail:='신규 지부가 등록되었습니다.'; end if;
  insert into gms_public_activity(organization_code,event_type,subject_masked,detail,source_table,source_id)
  values(v_org,v_type,gms_mask_name(v_name),v_detail,tg_table_name,coalesce(j->>'id',''));
  return new;
end $$;

-- 존재하는 테이블에만 트리거 생성
DO $$
declare t text; trg text;
begin
  foreach t in array array['ipma_member_applications','wtkf_member_applications','idp_member_applications','idp_branch_applications'] loop
    if to_regclass('public.'||t) is not null then
      trg:='trg_gms_feed_'||t;
      execute format('drop trigger if exists %I on public.%I',trg,t);
      execute format('create trigger %I after insert or update of status on public.%I for each row execute function public.gms_feed_from_application()',trg,t);
    end if;
  end loop;
end $$;

