create or replace function public.gms_mask_name(p_name text)
returns text language plpgsql immutable as $$
declare n text := trim(coalesce(p_name,'')); l int;
begin
  l := char_length(n);
  if l = 0 then return '회원'; end if;
  if l = 1 then return n || '*'; end if;
  if l = 2 then return substr(n,1,1) || '*'; end if;
  return substr(n,1,1) || repeat('*',greatest(l-2,1)) || substr(n,l,1);
end $$;

-- 홈페이지용 공개 통계: 개인정보는 반환하지 않습니다.
create or replace function public.gms_get_public_stats(p_organization_code text default null)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_org text := upper(nullif(trim(p_organization_code),''));
  v_legacy bigint := 0;
  v_unique bigint := 0;
  v_online bigint := 0;
  v_approved bigint := 0;
  v_activity30 bigint := 0;
  v_table text;
begin
  select count(*) into v_legacy from gms_legacy_members
   where status <> 'inactive' and (v_org is null or organization_code=v_org);
  select count(distinct person_key) into v_unique from gms_legacy_members where status <> 'inactive';
  select count(*) into v_online from members where coalesce(status,'active') <> 'inactive';

  if v_org='IPMA' then v_table:='ipma_member_applications';
  elsif v_org='WTKF' then v_table:='wtkf_member_applications';
  elsif v_org='IDP' then v_table:='idp_member_applications';
  end if;
  if v_table is not null and to_regclass('public.'||v_table) is not null then
    execute format('select count(*) from public.%I where lower(coalesce(status::text,''''))=''approved''',v_table) into v_approved;
  end if;

  select count(*) into v_activity30 from gms_public_activity
   where is_public=true and occurred_at >= now()-interval '30 days'
     and (v_org is null or organization_code=v_org);

  return jsonb_build_object(
    'organization_code',v_org,
    'legacy_members',v_legacy,
    'legacy_unique_people',v_unique,
    'online_members_total',v_online,
    'approved_applications',v_approved,
    'activity_30d',v_activity30
  );
end $$;

revoke all on function public.gms_get_public_stats(text) from public;
grant execute on function public.gms_get_public_stats(text) to anon, authenticated;

create or replace function public.gms_get_public_activity(p_organization_code text default null, p_limit integer default 12)
returns table(id bigint,organization_code text,event_type text,subject_masked text,detail text,occurred_at timestamptz)
language sql
security definer
set search_path=public
as $$
  select a.id,a.organization_code,a.event_type,a.subject_masked,a.detail,a.occurred_at
  from gms_public_activity a
  where a.is_public=true
    and (nullif(upper(trim(p_organization_code)),'') is null or a.organization_code=upper(trim(p_organization_code)))
  order by a.occurred_at desc
  limit greatest(1,least(coalesce(p_limit,12),50));
$$;
revoke all on function public.gms_get_public_activity(text,integer) from public;
grant execute on function public.gms_get_public_activity(text,integer) to anon, authenticated;

