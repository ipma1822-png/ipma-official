window.IPMA_CERTIFICATION_REGULATIONS_TEXT.zh=`第1条【目的】
本规定旨在确定国际警察武道联合会（IPMA，以下简称“本会”）所管理的段·级、指导者资格、教育课程、各类认证以及相关审查、登记和签发的基本标准与程序，以建立本会认证体系的公正性、可信性和持续管理机制。

第2条【适用范围】
① 本规定适用于由本会直接管理，或以本会名义和权限实施的段·级审查、指导者及相关资格、教育课程认证、组织·机构认证以及其他认证、审查、登记和签发业务。
② 除另有特别规定外，本规定亦适用或准用于包括世界跆拳剑道联盟（WTKF）在内由本会设立或批准的所属机构的段·级、资格及认证业务。
③ 因项目或资格特性需要另行制定审查标准或教育课程时，可在不违反本规定的范围内制定详细标准。
④ 本规定不改变或取代本会章程及内部规约中有关段证、资格和认证权限及基本原则的规定。

第3条【认证基本原则】
① 本会的段证、资格证、认证书及其他官方证书，原则上须依规定标准和程序经过审查、核实及批准后签发。
② 段·级、资格和认证不仅是名誉或持有证书，而是对相关领域经确认的修炼、教育、活动、经历或资格进行正式记录和管理的制度。
③ 审查及认证不得因国籍、种族、性别、社会地位或私人关系等进行不当歧视。
④ 不得仅因本会职务、私人关系、赞助、捐赠或其他关系而任意免除正常审查、认证标准或自动授予资格。
⑤ 内部规约或其他官方标准认可的名誉段、认可段、国际合作、公益目的等特别认证，可依其性质另行适用相应程序和标准。

第4条【段证分类】
① 本会认可的段证可依内部规约分为正式段证、认可段证及名誉段证等。
② 正式段证原则上应经过本会或本会认可的正式修炼、教育及审查体系的审查后签发。
③ 对在其他武道团体或机构取得的段位、经历、修炼经历或相当经验，本会核实审查后认可其全部或部分时，可签发认可段证。
④ 对在本会发展、国际交流、社会贡献、武道发展或其他特殊功绩方面被认可具有贡献或必要性者，可依内部规约及批准程序授予名誉段证。
⑤ 获得认可段或名誉段本身并不自动授予本会内指导者资格、审查权、职务、组织运营权或收益权利。

第5条【最终签发及批准权限】
① 正式段证、资格证、认证书及其他同等证书的最终签发，依本会章程、内部规约及权限体系执行。
② 所属机构、国内外分支、指导者、审查委员或其他人员，不得超越总部授予的权限范围独立签发或最终确认本会官方证书。
③ 指导者、审查委员、国家代表、分支负责人或所属机构负责人的推荐或审查本身，不构成官方签发的最终确定。
④ 总部可在核实申请、审查结果、经历、既有资格、登记信息及其他必要事项后决定最终是否签发。
⑤ 未经本会批准制作、签发的证书，或以足以误认为本会官方证书的形式制作的证书，可不被认可为官方签发记录。

第6条【申请与受理】
① 申请段·级、资格或认证者，原则上应通过总部或所属机构、国内外分支、指导者、审查委员等本会认可的正式渠道提出申请。
② 可要求申请人提交姓名、出生日期、联系方式、所属、申请项目或资格、现有段·级或资格、修炼、教育及活动经历，以及总部要求的其他信息。
③ 对认可段、经历认可、转换或既有资格登记，可要求提交原有段·资格证、结业证、经历证明及其他可核实材料。
④ 申请或提交材料存在虚假、篡改或重大遗漏时，总部可暂停或拒绝审查或签发；签发后发现的，可依相关规定重新审查。
⑤ 申请被受理或缴纳费用本身，不表示已确定取得段·级、资格或认证。

第7条【修炼、教育及经历核实】
① 审查段·级、资格及认证时，可依项目或资格特性综合核实修炼期间、完成教育、技术水平、指导经历、活动经历、既有段·级或资格及其他必要事项。
② 所需修炼期间、教育时数、晋段最低期限、课程及技术标准，可按项目和资格另行制定详细标准。
③ 在海外或其他机构取得的经历和资格，可综合考虑签发机构、取得时间、活动内容、可核实性及与本会标准的可比性，认可其全部或部分。
④ 仅凭提交材料难以核实时，总部或有权限的审查委员可要求追加材料、说明、实技确认、面谈或其他合理核实程序。
⑤ 长期武道经历或拥有其他团体高段位、职务，并不当然取得本会同等段·级或资格。

第8条【审查方法】
① 审查可依段·级或资格性质，采用实技、理论、口试、文件、教育履修、活动经历、指导能力等一种或多种适当方法。
② 具体审查项目和方法可综合项目、阶段、资格、年龄、教育目的及审查环境等确定。
③ 即使以现场审查为原则，如存在国际距离、灾害、健康、设施等合理原因，也可在总部认可范围内采用视频、线上审查、材料提交等适当方式。
④ 审查委员不得因私人关系、感情、金钱关系或组织地位而不当调整审查结果。
⑤ 审查结果除合格或不合格外，必要时可要求补充、重新审查、追加教育或追加材料。

第9条【高段位及高级资格审查】
① 高段位及高级指导者、审查资格原则上应比一般段·级或基础资格进行更审慎的审查。
② 除技术水平外，可综合考虑修炼和指导经历、对武道发展的贡献、活动实绩、作为指导者的品行与责任、既有资格的可信性及其他必要事项。
③ 仅因在其他团体拥有同等或更高段位，并不自动授予本会同等高段位。
④ 对具有特殊经历、功绩或国际武道经验者，在核实相关材料后，可依本会内部规约及批准程序，以认可段或其他适当方式进行审查。
⑤ 高段位或高级资格的最终认可与签发须依本会权限体系取得最终批准，不得仅凭一般推荐或地方组织自行决定而确定。

第10条【其他团体段位、资格及经历的认可】
① 本会可应申请人请求或根据需要，核实审查其从其他武道团体、教育机构、公共机构或相关组织取得的段证、资格、教育及活动经历。
② 认可时可考虑该机构是否真实存在、签发内容、取得过程、项目关联性、修炼与指导经历、活动期间及可核实材料等。
③ 本会可按同等水平认可其他团体的段·级或资格，也可仅认可部分，或要求另行审查、教育或补充。
④ 对其他团体证书的认可，不得解释为本会对该团体整体或其签发的全部证书作出正式批准、合作或保证。
⑤ 虚假、伪造或难以核实正常签发事实的材料，可排除在认可依据之外。

第11条【审查委员及指导者权限】
① 本会段·级、资格及认证的审查，原则上由总部或本会认可、任命、批准的审查委员、指导者及其他相关人员实施。
② 审查委员和指导者应在总部授予或相关项目、资格标准认可的范围内进行审查、评价及推荐。
③ 拥有特定段·级或资格本身，并不自动获得对本会所有项目、阶段和资格的审查权。
④ 担任国家代表、分支负责人、所属机构负责人或役员等职务本身，并不授予独立签发权或无限审查权。
⑤ 审查或指导权限范围另有规定时，不得超越该范围进行审查或确定性承诺本会批准。

第12条【推荐、审查与最终批准的分离】
① 本会认可的指导者、审查委员、国家代表、分支负责人或所属机构负责人，可在权限范围内核实申请人的修炼、教育及经历并实施审查或推荐。
② 地方或所属机构的审查结果和推荐，可作为总部最终批准判断的资料。
③ 通过审查或获得推荐本身，并不最终确定签发本会官方证书。
④ 总部在最终批准时可核实申请、审查结果、既有段·级·资格、登记状态及其他必要事项，并要求补充或追加核实。
⑤ 官方签发及最终登记依本会章程、内部规约及权限体系执行。

第13条【审查结果、补充与重新审查】
① 审查结果可依项目或资格标准处理为合格、不合格、补充、追加教育或重新审查等。
② 能力或提交材料不足但可合理补充时，可提供追加教育、材料补充或重新审查机会。
③ 重新审查的方法和范围可综合不足项目、项目或资格特性及申请人情况等确定。
④ 发现重大错误、虚假材料、不当行为或严重程序问题时，总部可在签发前重新审查结果。
⑤ 获得审查或重新审查机会本身，并不保证合格或签发。

第14条【证书签发与官方登记】
① 经本会最终批准的段·级、资格或认证，可依制度签发为正式段证、资格证、认证书、卡片或其他证书。
② 官方签发时，可登记和管理姓名、出生日期、段·级或资格名称、签发编号、签发日期、所属、项目及其他必要信息。
③ 纸质证书、卡片、电子证书或其他形式，如基于同一官方登记记录，可在本会规定范围内认可为官方证书。
④ 因遗失、损坏、姓名变更、标注错误或其他合理原因，可依总部程序申请补发或更正。
⑤ 持有证书本身并不自动证明现任职务、审查权、指导权或组织运营权，此类权限须通过另行任命、登记或资格状态确认。

第15条【官方查询与真实性核实】
① 本会可为确保证书可信性和核实真实性，运营官方登记和查询系统。
② 官方查询信息在考虑个人信息保护的前提下，可显示姓名、段·级或资格、证书编号、签发或登记状态以及总部认为需要公开的其他信息。
③ 证书信息与本会官方登记记录不一致时，可核实事实并以本会最终官方登记记录为准进行整理。
④ 伪造或篡改的证书、不存在的签发编号或与本会官方登记无关而自行制作的证书，不认可为官方认证。
⑤ 机构、团体、雇主、会员或其他人员提出请求时，总部可在考虑个人信息保护和相关标准后，在必要范围内核实真实性。
⑥ 因个人信息或安全原因可限制部分登记信息公开，仅因未公开并不否定证书或认证效力。

第16条【审查、登记及签发费用】
① 可就段·级、资格及认证相关的审查、登记、教育、证书或卡片签发、配送及其他必要事项制定费用。
② 费用可依项目、段·级或资格种类、审查方式、签发形式、国家或地区、国际配送及其他运营条件有所不同。
③ 总部可因国际合作、公益目的、特殊功绩、组织发展、需要支援的情形或其他合理原因，减免全部或部分相关费用。
④ 费用差异、减免属于综合申请和签发性质及情况作出的运营判断，不当然产生他人要求相同条件的权利。
⑤ 缴纳费用本身并不保证合格、段·级认可、资格取得或官方证书签发。

第17条【费用收取及地方运营】
① 以本会名义收取与段位、资格或认证有关费用时，应依总部批准或规定的程序和范围执行。
② 所属机构、国内外分支、指导者或其他相关人员代总部收取费用时，应在批准目的和范围内处理。
③ 地方组织自行提供的教育、设施运营、活动或其他服务费用，原则上应与总部官方审查、登记及签发费用区分。
④ 不得将地方自行确定的收费虚假或误导性地表示为总部强制规定的官方费用。
⑤ 总部必要时可要求核实以本会名义收取的审查、登记和签发费用明细及处理情况。

第18条【虚假材料、不当审查及不当取得】
① 申请人不得为取得段·级、资格或认证而提交虚假经历、段·资格证、教育经历、活动材料或其他不实材料。
② 不得使用他人身份或证书，亦不得伪造或篡改文件、电子记录、照片、签发编号等用于申请或认证。
③ 审查委员、指导者、役员及相关人员不得因金钱、私人关系、请托、压力或私利制作虚假审查结果、推荐、经历确认或签发材料。
④ 为规避正常审查、批准程序而故意串通取得或签发证书时，可分别审查申请人及相关人员的行为。
⑤ 怀疑存在虚假或不当行为时，总部可要求必要材料或说明，并暂停审查、登记或签发。

第19条【签发记录的更正、复核与撤销】
① 官方登记或签发记录中的简单事务、录入错误、姓名变更或其他可客观核实的错误，可经确认后更正。
② 签发后发现虚假材料、伪造篡改、不当审查、重大程序违反或签发时不具备资格条件等严重问题时，总部可复核认证或签发记录。
③ 经复核确认签发所依据的重要事实虚假或未满足正常签发条件时，可依相关规定和本会权限体系采取更正、暂停效力、撤销或其他措施。
④ 在作出造成重大不利益的最终措施前，除紧急情形或明显伪造等特殊情况外，原则上应通知本人并给予合理说明或提交材料的机会。
⑤ 通过正常程序取得的既往段位或资格，不得仅因私人纠纷、组织内部意见冲突或职务终止而任意撤销。
⑥ 职务或任命的有效性与段位或资格的有效性原则上分别判断。

第20条【个人信息及认证记录管理】
① 本会可管理段·级、资格及认证申请、审查、登记、签发、补发及真实性核实所需信息。
② 管理信息可包括姓名、出生日期、联系方式、照片、所属、段·级、资格、证书编号、签发日期、审查、教育、经历信息及其他认证业务所需事项。
③ 个人信息和认证记录应在认证业务、官方查询、真实性核实、记录保存及其他正当运营目的范围内处理。
④ 运营公开查询服务时，可综合个人信息保护与认证可信性确定公开信息范围。
⑤ 即使照片、联系方式、出生日期等部分信息限制公开，只要总部存在有效官方登记记录，不因该限制本身否定认证效力。
⑥ 总部可为保持官方签发、登记记录的连续性和真实性核实，以合理方式保存和管理记录。

第21条【名誉段及特别认证】
① 本会可依内部规约规定的标准和权限，对在本会发展、国际交流、社会贡献、武道发展或其他特别贡献方面被认可具有特殊功绩或必要性者，授予名誉段证或同等特别认证。
② 名誉段和特别认证的性质与目的可不同于通过通常修炼及晋段审查取得的正式段位，并可依其目的适用另行审查、推荐及批准程序。
③ 确定名誉段或特别认证等级时，可综合授予目的、经历、功绩、社会贡献、国际交流及与本会关系等因素。
④ 授予名誉段或特别认证本身，并不自动授予指导者资格、审查权、段证签发权、国家代表、分支负责人、役员等职务、组织运营权或收益权利。
⑤ 获得者不得虚假表示其性质，或使人误认为其为通过通常实技审查取得的资格或本会官方职务。

第22条【段位、资格、认证与职务的分离】
① 段·级、指导者资格、审查资格、其他专业资格、官方职务及组织代表权限，原则上依各自性质和授予程序分别管理。
② 拥有高段位本身，并不自动授予指导者资格、审查权、段证签发权或本会役员、国家代表、分支负责人等职务。
③ 拥有指导者或审查资格本身，并不产生代表本会组织的权限或对特定国家、地区的独占权限。
④ 担任国家代表、分支负责人、役员或所属机构负责人等职务本身，并不自动授予高段位或其他专业资格。
⑤ 各段位、资格、认证和职务的有效性，以相关领域的官方登记、签发或任命记录及当前状态为准进行确认。

第23条【所属机构及国内外组织的认证业务】
① 包括WTKF在内的所属机构及国内外官方组织，可在总部批准或委托范围内执行教育、审查、推荐、申请受理及其他认证相关业务。
② 所属机构或国内外组织需要自身项目、教育课程或资格体系时，可在不违反本会章程、内部规约及本规定的范围内另行制定详细标准。
③ 所属机构、国家代表、分支或指导者自行实施的教育或审查如涉及签发本会官方证书，应遵循总部规定的登记和批准程序。
④ 不得超越总部批准或委托范围，使用本会名称、标志、证书样式、签发编号或类似要素独立制作或签发官方证书。
⑤ 海外认证业务除遵守本会标准外，还应遵守所在国家或地区的相关法律法规。
⑥ 总部为确保认证体系可信性或正常运营，必要时可核实所属机构及国内外组织有关审查、登记、签发的运营情况和记录。

第24条【异议与说明】
① 申请人或认证相关人员认为审查、登记、签发、更正、暂停或撤销存在重大事实错误或程序问题时，可请求总部核实事实或复核。
② 接到复核请求时，总部可在必要范围内核实既有审查材料、登记记录、提交材料及当事人说明等。
③ 必要时可另行征求原审查委员以外人员或有权限负责人的意见。
④ 提出复核请求本身，并不自动改变既有审查结果或登记状态的效力。
⑤ 复核确认明显错误时可予更正；认为原决定适当时可维持原决定。
⑥ 不得仅因提出异议或说明而给予申请人或相关人员不当不利益。

第25条【官方公开及现行标准管理】
① 本会可在官方网站公开本规定现行内容，使会员、指导者、所属机构及国内外相关人员能够确认当前适用的认证和审查标准。
② 依本会正式程序确定并在官方网站公布的现行规定，作为当前适用的官方公开版本管理。
③ 各项目晋段最低期限、技术审查项目、教育时数、资格条件、签发程序及其他详细事项，可依相关制度特性另行制定详细标准、教育课程或运营指南。
④ 本规定或相关详细标准的实质内容需要变更时，应依本会章程、内部规约及内部决策程序确定后反映于现行标准。
⑤ 网站单纯技术修改、错别字更正、显示方式变更或管理员编辑行为，不视为规定实质内容的变更。
⑥ 既往签发记录、审查材料、内部标准及其他需要保存的资料，可由总部另行管理。

附则
第1条【适用】
本现行认证·审查标准，是适用于本会管理的段·级、指导者及相关资格、教育课程、各类认证以及相关审查、登记、签发业务的共同标准。

第2条【既有段位、资格及认证】
本规定适用前由本会依正常程序签发或批准的段证、资格证、认证书及其他官方记录，原则上维持签发或批准当时的事实及效力。
但确认存在虚假、伪造、篡改、不当取得或重大签发瑕疵时，可依本规定及相关标准重新审查。

第3条【既有所属机构及海外组织】
此前已开展本会段·级、资格或认证业务的所属机构、国内外分支及官方组织，可依本规定整理现有审查、推荐、登记、签发权限及运营方式。

第4条【详细标准】
因项目、段·级、资格、教育课程或认证特性，需要具体审查项目、晋段最低期限、教育时数、报考条件、审查委员资格或其他详细标准时，总部或有权限的所属机构可在不违反本规定的范围内另行制定详细标准。

第5条【与其他规定的关系】
本规定未规定的事项，依本会章程、内部规约、安全·伦理规定、国际组织及海外分支运营规定以及相关领域标准执行。`;